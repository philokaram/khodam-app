<?php
declare(strict_types=1);

/**
 * index.php — نقطة الدخول الرئيسية
 */

// ============================================================
// 1. BASE_PATH
// ============================================================
if (!defined('BASE_PATH')) {
    define('BASE_PATH', __DIR__);
}

// ============================================================
// 2. إنشاء المجلدات الأساسية
// ============================================================
foreach (['storage', 'storage/logs', 'storage/uploads', 'storage/exports'] as $dir) {
    $path = BASE_PATH . '/' . $dir;
    if (!is_dir($path)) @mkdir($path, 0755, true);
}

// ============================================================
// 3. env + .env
// ============================================================
require BASE_PATH . '/app/helpers/env.php';
loadEnv(BASE_PATH . '/.env');

// ============================================================
// 4. constants
// ============================================================
require BASE_PATH . '/app/config/constants.php';

// ============================================================
// 5. تحميل كل helpers (بما فيها response, auth, session, database...)
// ============================================================
require BASE_PATH . '/app/helpers/autoload.php';
loadAllHelpers();

// ============================================================
// 6. معالج الأخطاء (بعد response.php ليكون apiError متاحاً)
// ============================================================
registerErrorHandlers();

// ============================================================
// 7. autoloader للكلاسات
// ============================================================
spl_autoload_register('appAutoload');

// ============================================================
// 8. الجلسة
// ============================================================
startSecureSession();

// ============================================================
// 9. الترجمات
// ============================================================
$GLOBALS['__lang'] = require BASE_PATH . '/resources/lang/ar.php';

// ============================================================
// 10. التوجيه
// ============================================================
require BASE_PATH . '/routes/web.php';